"""Ports: the interfaces the application layer needs. Integration and data layers implement them."""

from __future__ import annotations

from datetime import datetime
from typing import Protocol
from uuid import UUID

from app.application.models import (
    AuthSession,
    Curriculum,
    CurriculumRules,
    GradesPeriod,
    Kardex,
    Requisite,
    Scenario,
    SchedulePeriod,
    StudentProfile,
    StudentRecord,
    Subject,
)


class SiiGateway(Protocol):
    async def login(self, email: str, password: str) -> str: ...
    async def get_profile(self, token: str) -> StudentProfile: ...
    async def get_kardex(self, token: str) -> Kardex: ...
    async def get_grades(self, token: str) -> list[GradesPeriod]: ...
    async def get_schedule(self, token: str) -> list[SchedulePeriod]: ...


class SessionRepository(Protocol):
    async def create(self, session: AuthSession) -> None: ...
    async def get(self, token_hash: str) -> AuthSession | None: ...
    async def get_by_refresh(self, refresh_hash: str) -> AuthSession | None: ...
    async def delete(self, token_hash: str) -> None: ...
    async def purge_expired(self, now: datetime) -> int: ...


class StudentRepository(Protocol):
    async def get(self, numero_control: str) -> StudentRecord | None: ...
    async def upsert(self, record: StudentRecord) -> None: ...


class CurriculumRepository(Protocol):
    async def get_active(self) -> Curriculum | None: ...
    async def get_active_id(self) -> int | None: ...
    async def list_subjects(self, curriculum_id: int) -> list[Subject]: ...
    async def get_subject(self, curriculum_id: int, clave: str) -> Subject | None: ...
    async def create_subject(self, curriculum_id: int, subject: Subject) -> Subject: ...
    async def update_subject(self, curriculum_id: int, subject: Subject) -> Subject: ...
    async def delete_subject(self, curriculum_id: int, clave: str) -> None: ...
    async def list_requisites(self, curriculum_id: int) -> list[Requisite]: ...
    async def add_requisite(self, curriculum_id: int, requisite: Requisite) -> Requisite: ...
    async def delete_requisite(self, curriculum_id: int, requisite_id: int) -> bool: ...
    async def get_rules(self, curriculum_id: int) -> CurriculumRules: ...
    async def update_rules(self, curriculum_id: int, rules: CurriculumRules) -> CurriculumRules: ...


class ScenarioRepository(Protocol):
    async def list_for_student(self, numero_control: str) -> list[Scenario]: ...
    async def get(self, scenario_id: UUID, numero_control: str) -> Scenario | None: ...
    async def create(self, scenario: Scenario) -> Scenario: ...
    async def update(self, scenario: Scenario) -> Scenario: ...
    async def delete(self, scenario_id: UUID, numero_control: str) -> bool: ...
